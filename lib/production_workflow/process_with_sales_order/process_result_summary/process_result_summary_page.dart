  }

  String get _totalProcessedText =>
      '$_totalProcessed / ${_batchQuantity ?? '-'} unit';

  String get _remainingBatchText => '${_remainingBatchQuantity ?? '-'} unit';

  String _dateText(Object? value) {
    if (value == null || value.toString().isEmpty) return '-';
    final parsed = DateTime.tryParse(value.toString());
    if (parsed == null) return value.toString();
    final date = parsed.toLocal();
    final hour = date.hour % 12 == 0 ? 12 : date.hour % 12;
    final period = date.hour < 12 ? 'am' : 'pm';
    final minute = date.minute.toString().padLeft(2, '0');
    final second =
        date.second == 0 ? '' : ':${date.second.toString().padLeft(2, '0')}';
    return '${date.year}-${date.month.toString().padLeft(2, '0')}-${date.day.toString().padLeft(2, '0')} | ${hour.toString().padLeft(2, '0')}:$minute$second$period';
  }

  String _problemText(int index) {
    final rows =
        (_processDetails['problems'] as List? ?? []).whereType<Map>().toList();
    if (index >= rows.length) return '';
    final problem = Map<String, dynamic>.from(rows[index]);
    final code = problem['code'] ?? problem['problem_code'];
    final name = problem['name'] ?? problem['problem_name'];
    final text = [code, name]
        .where((value) => value != null && value.toString().isNotEmpty)
        .join(' - ');
    return text.isEmpty ? 'Problem ${problem['problem_id'] ?? ''}' : text;
  }

  String get _remarksText {
    final value = _processDetails['remarks']?.toString().trim();
    return value == null || value.isEmpty ? 'No remarks recorded.' : value;
  }

