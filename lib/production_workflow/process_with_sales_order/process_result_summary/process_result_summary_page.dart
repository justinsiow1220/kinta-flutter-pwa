  Future<void> _loadProcessDetails() async {
    final draft = KintaProcessDraft.instance;
    Map<String, dynamic>? local;
    if (draft.localProcessId != null) {
      try {
        local =
            await KintaLocalRepository.readLocalProcess(draft.localProcessId!);
      } catch (_) {}
    }
    Map<String, dynamic>? server;
    if (draft.processId != null) {
      try {
        server = await KintaApiService.getMap('processes/${draft.processId}');
      } catch (_) {}
    }
    if (!mounted) return;
    final details = <String, dynamic>{...?local, ...?server};
    for (final field in ['problems', 'qc_inspections', 'pic_history']) {
      final serverRows = server?[field];
      final localRows = local?[field];
      if ((serverRows is! List || serverRows.isEmpty) && localRows is List) {
        details[field] = localRows;
      }
    }
    setState(() => _processDetails = details);
  }

  int? _asInt(Object? value) =>
      value is int ? value : int.tryParse(value?.toString() ?? '');

  int get _totalProcessed {
    final draft = KintaProcessDraft.instance;
    final passed =
        _asInt(_processDetails['qty_passed']) ?? draft.qtyPassed ?? 0;
    final rejected =
        _asInt(_processDetails['qty_rejected']) ?? draft.qtyRejected ?? 0;
    return passed + rejected;
  }

  int? get _batchQuantity =>
      _asInt(_processDetails['batch_qty']) ??
      KintaProcessDraft.instance.batchQty;

  int? get _remainingBatchQuantity {
    final batch = _batchQuantity;
    return batch == null
